"""Write ``results/sensitivity.md``: the ranking under other success tolerances.

uv run python -m faultladder.sensitivity
"""

import argparse
from pathlib import Path

from faultladder import score
from faultladder.evaluate import summarize
from faultladder.gate import BASELINES, load_baselines


def build(results: str | Path) -> str:
    """FaultLadder score of each baseline at each multiple of the tolerances."""
    runs = {name: r for name, r in load_baselines(Path(results)).items() if r}
    if len(runs) < 2:
        raise ValueError(f"need at least two baselines under {results}")
    table: dict[str, dict[float, float]] = {}
    for name, reports in runs.items():
        table[name] = {}
        for scale in score.TOLERANCE_SCALES:
            scores = [summarize(r["cells"], scale) for r in reports]
            if any(s is None for s in scores):
                raise ValueError(f"{name} has an incomplete ladder")
            values = [s["faultladder"] for s in scores if s is not None]
            table[name][scale] = sum(values) / len(values)
    names = sorted(table, key=lambda name: -table[name][1.0])
    reference = [table[name][1.0] for name in names]
    header = " | ".join(f"{scale:g}x" for scale in score.TOLERANCE_SCALES)
    lines = [
        "# Sensitivity to the success tolerances",
        "",
        f"FaultLadder score (mean across seeds) when both tolerances "
        f"({score.LIN_TOL} m/s and {score.ANG_TOL} rad/s) are multiplied by a "
        "factor. The last row is Kendall's tau between that column's ranking "
        "and the 1x ranking; 1.000 means the same order. Generated by "
        "`uv run python -m faultladder.sensitivity`; do not edit by hand.",
        "",
        f"| Policy | {header} |",
        "| --- |" + " --- |" * len(score.TOLERANCE_SCALES),
    ]
    for name in names:
        row = " | ".join(f"{table[name][s]:.3f}" for s in score.TOLERANCE_SCALES)
        lines.append(f"| {BASELINES[name]} | {row} |")
    taus = " | ".join(
        f"{score.rank_agreement(reference, [table[n][s] for n in names]):.3f}"
        for s in score.TOLERANCE_SCALES
    )
    lines.append(f"| Rank agreement | {taus} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="results")
    parser.add_argument("--out", default="results/sensitivity.md")
    args = parser.parse_args()
    report = build(args.results)
    Path(args.out).write_text(report)
    print(report)


if __name__ == "__main__":
    main()
