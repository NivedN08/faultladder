"""Write ``results/tracks.md`` from the saved onset and compound runs.

uv run python -m faultladder.tracks_report
"""

import argparse
import json
from pathlib import Path
from typing import Any

from faultladder import score
from faultladder.gate import BASELINES


def load_tracks(results: str | Path) -> dict[str, list[dict[str, Any]]]:
    """Every ``ppo_<baseline>_seed<n>/tracks.json`` under ``results``."""
    runs: dict[str, list[dict[str, Any]]] = {}
    for name in BASELINES:
        paths = sorted(Path(results).glob(f"ppo_{name}_seed*/tracks.json"))
        if paths:
            runs[name] = [json.loads(p.read_text()) for p in paths]
    return runs


def _stat(values: list[float]) -> str:
    mean = sum(values) / len(values)
    if len(values) < 2:
        return f"{mean:.3f}"
    return f"{mean:.3f} ± {score.interval(values):.3f}"


def build(results: str | Path) -> str:
    """Both tracks as Markdown: mean ± 95% confidence interval across seeds."""
    runs = load_tracks(results)
    if not runs:
        raise ValueError(f"no tracks.json under {results}")
    protocol = {
        (r["tracks"], r["ladder"], r["episodes_per_cell"])
        for reports in runs.values()
        for r in reports
    }
    if len(protocol) != 1:
        raise ValueError(f"the runs differ in tracks, ladder or episodes: {protocol}")
    tracks, ladder, episodes = next(iter(protocol))
    names = sorted(
        runs,
        key=lambda n: (
            -sum(r["scores"]["compound"]["compound"] for r in runs[n]) / len(runs[n])
        ),
    )
    lines = [
        "# FaultLadder tracks",
        "",
        f"Unitree Go1, tracks {tracks}, ladder {ladder}, {episodes} episodes per "
        "cell. Each entry is the mean across training seeds ± the half-width of "
        "its 95% confidence interval. Generated by "
        "`uv run python -m faultladder.tracks_report`; do not edit by hand.",
        "",
        "## Compound: two axes perturbed together",
        "",
        "Predicted is the success expected if the two faults hurt "
        "independently, from the same policy's single-fault cells. Interaction "
        "is compound minus predicted.",
        "",
        "| Policy | Seeds | Compound | Predicted | Interaction |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in names:
        stats = " | ".join(
            _stat([r["scores"]["compound"][k] for r in runs[name]])
            for k in ("compound", "predicted", "interaction")
        )
        lines.append(f"| {BASELINES[name]} | {len(runs[name])} | {stats} |")
    lines += [
        "",
        "### Interaction per pair (compound minus predicted, both levels)",
        "",
        "| Pair | " + " | ".join(BASELINES[n] for n in names) + " |",
        "| --- |" + " --- |" * len(names),
    ]
    first = runs[names[0]][0]["compound_cells"]
    pairs = list(dict.fromkeys((c["a"], c["b"]) for c in first))

    def interaction(name: str, pair: tuple[str, str]) -> float:
        values = [
            c["observed"] - c["predicted"]
            for r in runs[name]
            for c in r["compound_cells"]
            if (c["a"], c["b"]) == pair
        ]
        return sum(values) / len(values)

    pairs.sort(key=lambda pair: sum(interaction(n, pair) for n in names))
    for pair in pairs:
        row = " | ".join(f"{interaction(n, pair):+.3f}" for n in names)
        lines.append(f"| {pair[0]} + {pair[1]} | {row} |")
    lines += [
        "",
        "## Onset: a motor fault that starts mid-episode",
        "",
        f"The fault appears {runs[names[0]][0]['onset_seconds']:g} s into the "
        "episode; static is the same cells with the fault present from the "
        "start, scored over the same window. Gap is static minus onset.",
        "",
        "| Policy | Seeds | Onset | Static | Gap |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in names:
        stats = " | ".join(
            _stat([r["scores"]["onset"][k] for r in runs[name]])
            for k in ("onset", "static", "gap")
        )
        lines.append(f"| {BASELINES[name]} | {len(runs[name])} | {stats} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="results")
    parser.add_argument("--out", default="results/tracks.md")
    args = parser.parse_args()
    report = build(args.results)
    Path(args.out).write_text(report)
    print(report)


if __name__ == "__main__":
    main()
