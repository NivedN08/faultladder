"""Write ``results/leaderboard.md`` from the saved ladder runs.

uv run python -m faultladder.leaderboard
"""

import argparse
from pathlib import Path
from typing import Any

from faultladder import score
from faultladder.gate import BASELINES, load, load_baselines


def _stat(values: list[float]) -> str:
    mean = sum(values) / len(values)
    if len(values) < 2:
        return f"{mean:.3f}"
    return f"{mean:.3f} ± {score.interval(values):.3f}"


def build(results: str | Path) -> str:
    """The leaderboard as Markdown: mean ± 95% confidence interval across seeds."""
    results = Path(results)
    rows: list[tuple[str, list[dict[str, Any]]]] = [
        (label, runs)
        for name, label in BASELINES.items()
        if (runs := load_baselines(results)[name])
    ]
    rows += [
        (name.capitalize() + " agent", [load(results / name)])
        for name in ("zero", "random")
        if (results / name / "ladder.json").exists()
    ]
    if not rows:
        raise ValueError(f"no ladder runs under {results}")
    rows.sort(
        key=lambda row: -sum(r["scores"]["faultladder"] for r in row[1]) / len(row[1])
    )
    first = rows[0][1][0]
    protocol = {(r["ladder"], r["episodes_per_cell"]) for _, runs in rows for r in runs}
    if len(protocol) != 1:
        raise ValueError(f"the runs differ in ladder or episodes per cell: {protocol}")
    lines = [
        "# FaultLadder leaderboard",
        "",
        f"Unitree Go1, ladder {first['ladder']}, {first['episodes_per_cell']} "
        "episodes per cell. Each entry is the mean across training seeds ± the "
        "half-width of its 95% confidence interval (Student t). Generated by "
        "`uv run python -m faultladder.leaderboard`; "
        "do not edit by hand.",
        "",
        "| Policy | Seeds | FaultLadder | Fault | Shift | Nominal | Fall rate |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    keys = ("faultladder", "fault", "shift", "nominal", "fall_rate")
    for label, runs in rows:
        stats = " | ".join(_stat([r["scores"][k] for r in runs]) for k in keys)
        lines.append(f"| {label} | {len(runs)} | {stats} |")
    lines += [
        "",
        "## Axis scores (mean success over levels 1 to 5)",
        "",
        "| Policy | " + " | ".join(score.AXES) + " |",
        "| --- |" + " --- |" * len(score.AXES),
    ]
    for label, runs in rows:
        stats = " | ".join(
            _stat([r["scores"]["axes"][axis] for r in runs]) for axis in score.AXES
        )
        lines.append(f"| {label} | {stats} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="results")
    parser.add_argument("--out", default="results/leaderboard.md")
    args = parser.parse_args()
    report = build(args.results)
    Path(args.out).write_text(report)
    print(report)


if __name__ == "__main__":
    main()
